CREATE TABLE clients (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_user_id bigint NOT NULL UNIQUE CHECK (telegram_user_id > 0),
    telegram_chat_id bigint NOT NULL,
    name text NOT NULL,
    username text,
    language text NOT NULL DEFAULT 'ru' CHECK (language IN ('ru', 'ko')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE admins (
    user_id bigint PRIMARY KEY REFERENCES clients(user_id),
    google_email text,
    role text NOT NULL DEFAULT 'admin' CHECK (role IN ('owner', 'admin', 'operator')),
    notifications_enabled boolean NOT NULL DEFAULT true,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE bookings (
    booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES clients(user_id),
    type text NOT NULL DEFAULT 'booking' CHECK (type IN ('booking', 'block')),
    status text NOT NULL DEFAULT 'hold'
        CHECK (status IN ('hold', 'pending', 'confirmed', 'cancelled', 'expired', 'completed')),
    dt_order timestamptz NOT NULL DEFAULT now(),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    occupied_until timestamptz NOT NULL,
    expires_at timestamptz,
    amount numeric(14,2) NOT NULL CHECK (amount >= 0),
    deposit_paid_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (deposit_paid_amount >= 0),
    balance_paid_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (balance_paid_amount >= 0),
    unit varchar(3) NOT NULL DEFAULT 'KRW' CHECK (unit ~ '^[A-Z]{3}$'),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT booking_times_valid CHECK (
        isfinite(starts_at) AND isfinite(ends_at) AND isfinite(occupied_until)
        AND starts_at < ends_at AND ends_at <= occupied_until
    ),
    CONSTRAINT booking_expiry_required CHECK (
        status NOT IN ('hold', 'pending') OR expires_at IS NOT NULL
    ),
    CONSTRAINT blocks_use_explicit_status CHECK (
        type <> 'block' OR status IN ('confirmed', 'cancelled', 'completed')
    ),
    CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
        tstzrange(starts_at, occupied_until, '[)') WITH &&
    ) WHERE (status IN ('hold', 'pending', 'confirmed'))
);

CREATE INDEX bookings_user_id_idx ON bookings(user_id);
CREATE INDEX bookings_starts_at_idx ON bookings(starts_at);
CREATE INDEX bookings_expires_at_idx ON bookings(expires_at)
    WHERE status IN ('hold', 'pending');

CREATE FUNCTION update_booking_version() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.version := OLD.version + 1;
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER bookings_updated BEFORE UPDATE ON bookings
FOR EACH ROW EXECUTE FUNCTION update_booking_version();
